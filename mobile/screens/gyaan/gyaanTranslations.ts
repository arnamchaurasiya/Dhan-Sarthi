export const getLessonTranslation = (
  topicId: string,
  lang: string,
  fallbackLesson: LessonDetail
): LessonDetail => {
  if (lang === 'English') return fallbackLesson;

  const effectiveId = fallbackLesson.topicId || topicId;
  const langOverrides =
    TRANSLATED_LESSONS[effectiveId]?.[lang] ||
    TRANSLATED_LESSONS[topicId]?.[lang];

  if (!langOverrides) {
    // Return original fallback lesson without ugly bracket prefixes
    return fallbackLesson;
  }

  return {
    ...fallbackLesson,
    ...langOverrides,
  };
};
